// The feature pins' matrix (doc/architecture/mission-22/feature-pins-brief.md): runs test/features, reads each pin's
// state from the run, and writes doc/architecture/feature-pins.md, by pillar: a feature met (every pin of it passes),
// partly (some met, some missing or unwritten), missing (a failing proof, nothing met) or unwritten (no scenario yet).
// A pin is "missing: …" (an it.failing proof of what cannot yet be done), "unwritten: …" (an it.todo), or met. A run
// with a real failure is said so at the head of the matrix: a pin met that broke, or a missing one that now passes
// (an it.failing whose inner test passed fails the run, and must be promoted to a pin met).
import { spawnSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';

type State = 'met' | 'missing' | 'unwritten' | 'broken';
interface Pin { feature: string; name: string; state: State }

class FeaturePins {
  static readonly out = 'doc/architecture/feature-pins.md';
  static readonly xml = '/tmp/kyrie-feature-pins.xml';
  static run(): Pin[] {
    spawnSync('bun', ['test', 'test/features', '--reporter=junit', `--reporter-outfile=${FeaturePins.xml}`],
      { stdio: 'ignore', env: { ...process.env, KYRIE_BROWSER: '' } });
    const xml = readFileSync(FeaturePins.xml, 'utf8'), pins: Pin[] = [];
    for (const m of xml.matchAll(/<testcase name="([^"]*)" classname="([^"]*)"[^>]*?(\/>|>([\s\S]*?)<\/testcase>)/g)) {
      const name = FeaturePins.unescape(m[1]!), feature = FeaturePins.unescape(m[2]!), body = m[4] ?? '';
      const state: State = /<skipped/.test(body) ? 'unwritten' : /<failure|<error/.test(body) ? 'broken'
        : name.startsWith('missing:') ? 'missing' : 'met';
      pins.push({ feature, name: name.replace(/^(missing|unwritten): /, ''), state });
    }
    return pins;
  }
  static unescape(s: string): string {
    return s.replace(/&quot;/g, '"').replace(/&apos;/g, '\'').replace(/&lt;/g, '<').replace(/&gt;/g, '>')
      .replace(/&amp;/g, '&');
  }
  // A feature's state, from its pins'.
  static state(pins: Pin[]): string {
    if (pins.some(p => p.state === 'broken')) { return 'broken'; }
    if (pins.every(p => p.state === 'met')) { return 'met'; }
    if (pins.some(p => p.state === 'met')) { return 'partly'; }
    return pins.some(p => p.state === 'missing') ? 'missing' : 'unwritten';
  }
  // How many features stand in one state.
  static count(pins: Pin[], features: string[], state: string): number {
    return features.filter(f => FeaturePins.state(pins.filter(p => p.feature === f)) === state).length;
  }
  // The head line: features and pins by state.
  static summary(pins: Pin[], features: string[]): string {
    const [met, partly, missing, unwritten, broken] = ['met', 'partly', 'missing', 'unwritten', 'broken']
      .map(state => FeaturePins.count(pins, features, state));
    const [pinsMet, pinsMissing, pinsUnwritten] = (['met', 'missing', 'unwritten'] as State[])
      .map(state => pins.filter(x => x.state === state).length);
    return `${features.length} features: ${met} met, ${partly} partly, ${missing} missing, ${unwritten} unwritten`
      + `${broken ? `, **${broken} broken**` : ''}. ${pins.length} pins: ${pinsMet} met, ${pinsMissing} missing `
      + `(a failing proof), ${pinsUnwritten} unwritten.`;
  }
  static write(pins: Pin[]): string {
    const features = [...new Set(pins.map(p => p.feature))].sort();
    const pillars = [...new Set(features.map(f => f.split(' › ')[0]!))];
    const lines = ['# Feature pins', '',
      'Generated by `bun scripts/feature-pins.ts` from `test/features` (see mission-22/feature-pins-brief.md).',
      'Do not edit. Each is placed on the feature atlas (feature-atlas.md, `bun scripts/feature-atlas.ts --write`).', '',
      FeaturePins.summary(pins, features), ''];
    for (const pillar of pillars) {
      lines.push(`## ${pillar}`, '');
      for (const f of features.filter(x => x.startsWith(`${pillar} › `))) {
        const of = pins.filter(p => p.feature === f);
        lines.push(`- **${f.split(' › ')[1]}**: ${FeaturePins.state(of)}`);
        for (const p of of) { lines.push(`  - ${p.state}: ${p.name}`); }
      }
      lines.push('');
    }
    return lines.join('\n');
  }
}

const pins = FeaturePins.run();
writeFileSync(FeaturePins.out, FeaturePins.write(pins));
console.log(`${FeaturePins.out}: ${pins.length} pins`);
