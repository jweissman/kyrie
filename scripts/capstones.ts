#!/usr/bin/env bun
// The capstone map (see doc/architecture/mission-21/capstones-brief.md): every feature of the owner's table, what is
// claimed, what a probe observes, the time it took, and the gaps; written to doc/architecture/mission-21/capstones.md.
//   bun scripts/capstones.ts [--write]
import { writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { Features, SECTIONS, type Status } from '../test/capstones/features';
import { Probes, type Seen } from '../test/capstones/probes';

export class Capstones {
  static async observe(id: string): Promise<{ seen?: Seen; ms: number }> {
    const probe = Probes.by[id], began = performance.now();
    return { ...probe ? { seen: await probe() } : {}, ms: performance.now() - began };
  }
  static async main(args: string[]): Promise<number> {
    const lines: string[] = [], tally: Record<Status, number> = { present: 0, partial: 0, absent: 0 };
    let total = 0;
    for (const [i, name] of SECTIONS.entries()) {
      lines.push(`\n## ${i + 1}. ${name}\\n`.replace('\\n', ''), '| Feature | Pri | Claimed | Observed | ms | Proof | Gap |', '|---|---|---|---|---:|---|---|');
      for (const f of Features.all.filter(x => x.section === i + 1)) {
        const { seen, ms } = await this.observe(f.id);
        tally[f.claim]++; total += ms;
        lines.push(`| ${f.name} | ${f.priority} | ${f.claim} | ${seen ? seen.status : 'not probed'} | ${ms.toFixed(0)} | ${f.proof.length} | ${f.gap ?? ''} |`);
      }
    }
    const p0 = Features.all.filter(f => f.priority === 'P0'), p0gaps = p0.filter(f => f.claim !== 'present');
    const head = `# Capstones: the map (generated by scripts/capstones.ts)\n\n${Features.all.length} features: ${tally.present} present, ${tally.partial} partial, ${tally.absent} absent; P0: ${p0.length - p0gaps.length} of ${p0.length} whole; probes ${Features.all.filter(f => Probes.by[f.id]).length}, ${(total / 1000).toFixed(1)} s in all.`;
    const out = [head, ...lines].join('\n') + '\n';
    if (args.includes('--write')) { writeFileSync(join(import.meta.dir, '..', 'doc/architecture/mission-21/capstones.md'), out); }
    console.log(out);
    return 0;
  }
}
if (import.meta.main) { process.exit(await Capstones.main(process.argv.slice(2))); }
