#!/usr/bin/env bun
// The terminal walked over real Westernesse, several worlds, origins, callings and styles of player, each run on its
// own: each transcript kept, readable, as a review artifact (doc/architecture/mission-21/terminal/), and a report of
// what each run's arrivals told: the mean, the median, the worst, and the aim said beside (the owner, 14 November:
// TM-01, TM-05). Plain text (no colour), as a pipe gets it.
//   bun scripts/terminal-walks.ts [--turns=30]
import { mkdirSync, writeFileSync } from 'node:fs';
import { DrawnWorld } from '../src/world/drawn-world';
import { NodeBundleSource } from '../src/campaign/node-bundle-source';
import { TerminalWalk } from '../src/cli/terminal-walk';
import { WalkStyle } from '../src/cli/walk-style';
import { ClauseLoad } from '../src/presentation/clause-load';
import type { CreatureGenerationContext } from '../src/content';

export interface Run { name: string; seed: string; origin: string; party: CreatureGenerationContext[];
  style: WalkStyle }

export class TerminalWalks {
  static readonly runs: Run[] = [
    { name: 'a1-debt-warrior-straight', seed: 'a1', origin: 'debt', style: WalkStyle.straight,
      party: [{ name: 'Wynn', raceId: 'human', classId: 'warrior' }] },
    { name: 'kite-wanderer-thief-wandering', seed: 'kite', origin: 'wanderer', style: WalkStyle.wandering,
      party: [{ name: 'Sly', raceId: 'human', classId: 'thief' }] },
    { name: '123-wanderer-mage-wandering', seed: '123', origin: 'wanderer', style: WalkStyle.wandering,
      party: [{ name: 'Aud', raceId: 'human', classId: 'mage' }] },
    { name: 'thorn-courier-cleric-straight', seed: 'thorn', origin: 'courier', style: WalkStyle.straight,
      party: [{ name: 'Odo', raceId: 'human', classId: 'cleric' }] },
  ];
  static async walk(run: Run, turns: number) {
    const session = await DrawnWorld.start(run.seed, { origin: run.origin, party: run.party }, NodeBundleSource.shared);
    const walked = await TerminalWalk.run(session, run.style, turns);
    return { walked, budget: TerminalWalk.budget(walked) };
  }
  static async main(args: string[]): Promise<number> {
    const turns = Number(args.find(a => a.startsWith('--turns='))?.slice(8) ?? 30);
    const dir = 'doc/architecture/mission-21/terminal';
    mkdirSync(dir, { recursive: true });
    const lines = ['| run | arrivals | mean | median | worst | aim (mean, beside) | words a sentence, unasked | heavy |',
      '|---|---|---|---|---|---|---|---|'];
    for (const run of this.runs) {
      const { walked, budget } = await this.walk(run, turns);
      writeFileSync(`${dir}/${run.name}.txt`, `${walked.transcript.join('\n')}\n`);
      lines.push(`| ${run.name} | ${budget.scenes} | ${budget.mean.toFixed(2)} | ${budget.median} | `
        + `${budget.worst.map(w => w.sentences).join(', ')} | ${budget.reference.toFixed(2)} | `
        + `${(budget.unasked.words / Math.max(1, budget.unasked.sentences)).toFixed(1)} | `
        + `${budget.unasked.heavy.length} of ${budget.unasked.sentences} |`);
    }
    writeFileSync(`${dir}/report.md`, `# Terminal walks\n\nGenerated by \`bun scripts/terminal-walks.ts\` (${turns} `
      + `turns a run): the sentences each arrival told on its own, run by run, and the clause load of all that was said `
      + `unasked (src/presentation/clause-load.ts: a heavy sentence passes ${ClauseLoad.words} words or `
      + `${ClauseLoad.joints} joints).\n\n${lines.join('\n')}\n`);
    console.log(lines.join('\n'));
    return 0;
  }
}
if (import.meta.main) { process.exit(await TerminalWalks.main(process.argv.slice(2))); }
