#!/usr/bin/env bun
// The painting corpus: every image in assets/images (authorized for this project; public-domain and CC0 works), read
// as images, not as file names. For each: its size and digest, what its own metadata says of it (the Web Gallery of
// Art's comment, Art UK's EXIF and IPTC captions, XMP), parsed into artist, title, date, medium and where it hangs; the
// concept it was filed under; and a small copy for the game (web/reader/paintings).
//   bun scripts/paintings.ts [dir]     writes data/paintings/registry.json, the copies, and doc/paintings/registry.md
import { createHash } from 'node:crypto';
import { mkdirSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { PaintingMetadata, type Painting, type Seen } from '../src/paintings/painting-metadata';
import seen from '../data/paintings/seen.json';
import { PaintingConcepts } from '../src/paintings/painting-concepts';
import { Credits } from '../src/paintings/credits';

class PaintingsTool {
  static readonly root = resolve(import.meta.dir, '..');
  static async run(dir: string) {
    const files = readdirSync(dir).filter(f => /\.jpe?g$/i.test(f)).sort();
    const out = resolve(this.root, 'web/reader/paintings'), large = join(out, 'large');
    mkdirSync(large, { recursive: true });
    const looked = (seen as unknown as { paintings: Record<string, Seen> }).paintings;
    mkdirSync(resolve(this.root, 'data/paintings'), { recursive: true });
    const entries: Painting[] = [];
    for (const file of files) {
      const bytes = readFileSync(join(dir, file)), id = file.replace(/\.jpe?g$/i, '');
      const meta = PaintingMetadata.read(new Uint8Array(bytes));
      const image = new Bun.Image(bytes.buffer.slice(bytes.byteOffset, bytes.byteOffset + bytes.byteLength));
      const small = await image.resize(320).webp({ quality: 70 }).bytes();
      writeFileSync(join(out, `${id}.webp`), small);
      // The large copy is the painting at the size it came, up to 800 wide: enough to fill a conversation.
      const big = await new Bun.Image(bytes.buffer.slice(bytes.byteOffset, bytes.byteOffset + bytes.byteLength))
        .resize(Math.min(800, meta.width)).webp({ quality: 78 }).bytes();
      writeFileSync(join(large, `${id}.webp`), big);
      if (!looked[id]) { throw new Error(`No record in data/paintings/seen.json of what ${id} shows`); }
      entries.push({ id, file, bytes: bytes.length, sha1: createHash('sha1').update(bytes).digest('hex'),
        width: meta.width, height: meta.height, ...PaintingMetadata.describe(meta), copy: `paintings/${id}.webp`,
        copyBytes: small.byteLength, large: `paintings/large/${id}.webp`, largeBytes: big.byteLength, seen: looked[id]!,
        concept: PaintingConcepts.of(id) });
    }
    const registry = { about: 'Every painting of the corpus in assets/images, read from the images themselves: what each one\'s own metadata says (source: wga-comment, artuk-exif, iptc, xmp, or none), parsed; the concept it was filed under and what that concept is in the game (concept.kind, concept.family, concept.backgrounds); and the small copy the game shows. Generated by bun scripts/paintings.ts; do not edit by hand.',
      count: entries.length, paintings: entries };
    writeFileSync(resolve(this.root, 'data/paintings/registry.json'), `${JSON.stringify(registry, null, 1)}\n`);
    // What the game carries of it: which paintings there are, and how each is credited where it is shown.
    // A title that ends by naming its painter ("…, attributed to Barend Graat") does not name them twice; what is not
    // a credit at all is left out (see Credits).
    const credits = Object.fromEntries(entries.filter(e => e.artist || e.title)
      .map(e => [e.id, Credits.clean([e.artist, e.artist ? e.title?.replace(`, ${e.artist}`, '') : e.title, e.date]
        .filter(Boolean).join(', '))]).filter(([, c]) => c));
    writeFileSync(resolve(this.root, 'data/paintings/likeness.json'), `${JSON.stringify({ about: 'Generated by bun scripts/paintings.ts: the paintings the game can show, by concept, and how each is credited.',
      ids: entries.map(e => e.id), people: entries.filter(e => e.concept.kind === 'person').map(e => e.id), credits,
      // The portraits of one person, by what they show: sex, age, station, era, and the face's height in the picture.
      sitters: Object.fromEntries(entries.filter(e => e.seen.form === 'portrait')
        .map(e => [e.id, [e.seen.sex, e.seen.age ?? '', e.seen.station ?? '', e.seen.era, e.seen.face ?? 25].join('|')])),
      // The station of whoever a painting shows, portrait or not (the farmer's field hand is labouring).
      stations: Object.fromEntries(entries.filter(e => e.seen.station).map(e => [e.id, e.seen.station])),
      // Where the face, or what matters, sits in the others, for cropping.
      faces: Object.fromEntries(entries.filter(e => e.seen.form !== 'portrait' && e.seen.face).map(e => [e.id, e.seen.face])) },
    null, 1)}\n`);
    writeFileSync(resolve(this.root, 'doc/paintings/registry.md'), PaintingConcepts.report(entries));
    console.log(`${entries.length} paintings; ${entries.filter(e => e.artist).length} with an artist; `
      + `${entries.filter(e => e.title).length} with a title; copies ${Math.round(entries.reduce((s, e) => s + e.copyBytes, 0) / 1024)} KiB`);
  }
}

mkdirSync(resolve(PaintingsTool.root, 'doc/paintings'), { recursive: true });
await PaintingsTool.run(resolve(PaintingsTool.root, process.argv[2] ?? 'assets/images'));
