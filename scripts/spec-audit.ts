#!/usr/bin/env bun
// The expensive specs, audited: for each spec file the kept times call expensive (over 15 s on CI), what it starts (a
// generated world, an authored campaign, a tiny world, nothing) and, case by case, what its assertions are about.
// The classes are the local semantics a tiny Kyr world can hold (effect, knowledge, legality, follow-state,
// navigation, atlas facet, combat, telling) and what only a whole world can (composition, persistence). A case whose
// assertions are all local is a candidate to move to `test/small`; one that touches persistence or the generated
// country itself stays. A keyword reading of the source, to steer the migration, not to decide it: the counts are
// the plan's measure (Mission 21's completion plan, §1).
//   bun scripts/spec-audit.ts [--over=15]
import { existsSync, readFileSync, writeFileSync } from 'node:fs';

type Kind = 'generated world' | 'authored campaign' | 'tiny world' | 'browser' | 'unit';
interface Audited { file: string; seconds: number; kind: Kind; cases: number; local: number; classes: Set<string> }

export class SpecAudit {
  static readonly classes: [string, RegExp][] = [
    ['persistence', /checkpoint|resume\(|SaveCodec|fromSave|transcript|replay/],
    ['composition', /WorldAssembler|placements|report\.region|\.region\b|Countries|generated|seed/],
    ['knowledge', /\bknows\b|'knows'|knowledge/],
    ['follow-state', /follow|gold|continues|undertaking|objectives|aims?\b/],
    ['legality', /choices\(\)|\.find\(|offered|legal|disabled|Unoffered/],
    ['navigation', /\bat\(|travel|go\(|exits|compass|enclosed|route|Itinerar/],
    ['atlas facet', /aspects|likeness|facet|Emphasis|pip/],
    ['combat', /fight|attack|\bhp\b|Battle|combat|dead/],
    ['telling', /page|told|situation|presence|exchange|narrat/],
    ['effect', /holds\(|world\.test|state\(|number\(|related\(/],
  ];
  static readonly drawn = new RegExp(['DrawnWorld\\.start', 'WorldAssembler\\.assemble', 'EngineHost', 'GeneratedWorld',
    'Keep\\.', 'Kept\\.drawn', 'Inn\\.start', 'House\\.start'].join('|'));
  static main(args: string[]): number {
    const over = Number(args.find(a => a.startsWith('--over='))?.slice(7) ?? 15) * 1000;
    const times = (JSON.parse(readFileSync('test/timings.json', 'utf8')) as { files: Record<string, number> }).files;
    const rows = Object.entries(times).filter(([f, ms]) => ms > over && existsSync(f))
      .map(([f, ms]) => this.audit(f, ms)).sort((a, b) => b.seconds - a.seconds);
    const cases = rows.reduce((n, r) => n + r.cases, 0), local = rows.reduce((n, r) => n + r.local, 0);
    const migrated = rows.filter(r => r.kind === 'tiny world' || r.kind === 'unit').length;
    const byKind = new Map<string, number>();
    for (const r of rows) { byKind.set(r.kind, (byKind.get(r.kind) ?? 0) + 1); }
    const lines = ['# The expensive specs, audited', '', `Generated by \`bun scripts/spec-audit.ts\` from the kept `
      + `times (test/timings.json): the spec files over ${over / 1000} s on CI, what each starts and what its cases `
      + 'assert. A keyword reading, to steer the migration (completion-plan.md §1).', '',
      `- ${rows.length} files, ${cases} cases; by what they start: `
        + `${[...byKind].sort((a, b) => b[1] - a[1]).map(([k, n]) => `${k} ${n}`).join(', ')}.`,
      `- **Cases whose assertions are all local semantics (candidates for a tiny world): ${local} of ${cases}.**`,
      `- Files already on a tiny world or no world: ${migrated}.`, '',
      '| file | s | starts | cases | local | about |', '|---|---|---|---|---|---|',
      ...rows.map(r => `| ${r.file.replace('test/', '')} | ${Math.round(r.seconds)} | ${r.kind} | ${r.cases} | `
        + `${r.local} | ${[...r.classes].join(', ')} |`)];
    writeFileSync('doc/architecture/mission-21/spec-audit.md', `${lines.join('\n')}\n`);
    console.log(lines.slice(4, 7).join('\n'));
    return 0;
  }
  private static audit(file: string, ms: number): Audited {
    const text = readFileSync(file, 'utf8');
    const kind: Kind = /browser|chromium|playwright/i.test(file + text.slice(0, 2000)) ? 'browser'
      : SpecAudit.drawn.test(text) ? 'generated world'
        : /PlaySession\.start|Journey\.start|Kept\.start|Campaign\.load|campaign\.json|Bowl\.start|Calamy/.test(text)
          ? 'authored campaign' : /Tiny\.start|SingleModule/.test(text) ? 'tiny world' : 'unit';
    const bodies = text.split(/\n\s*it(?:\.each\([^)]*\))?\(/).slice(1);
    const classes = new Set<string>();
    let local = 0;
    for (const body of bodies) {
      const of = this.classes.filter(([, re]) => re.test(body)).map(([c]) => c);
      of.forEach(c => classes.add(c));
      if (!of.includes('persistence') && !of.includes('composition')) { local++; }
    }
    return { file, seconds: ms / 1000, kind, cases: bodies.length, local, classes };
  }
}
if (import.meta.main) { process.exit(SpecAudit.main(process.argv.slice(2))); }
