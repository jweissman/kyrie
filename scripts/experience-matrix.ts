// The experience measures' baseline (the owner, 15 November): blind walks through the runner, every calling on one
// origin a seed (so that callings can be paired on the same world and the same reason for being there), on a1, b2
// and c3 made through the real entry point (TerminalMatrix.made), and in the laboratory; each walk's Experience
// (src/cli/runner-experience.ts), the round's sums, the pairing, and a few short transcripts, written to
// doc/architecture/mission-21/terminal/experience.md. Baselines first: no thresholds yet. Regenerate with
//   bun scripts/experience-matrix.ts [--seeds a1,b2,c3] [--turns 30] [--policy curious] [--no-lab] [--out file]
import { writeFile } from 'node:fs/promises';
import { Runner } from '../src/cli/runner';
import { RunnerWalk, type Policy, type Walk } from '../src/cli/runner-walk';
import { RunnerExperience, type Experience } from '../src/cli/runner-experience';
import { PlayTool } from '../src/cli/play-tool';
import { Laboratory } from './laboratory';
import { TerminalMatrix } from './terminal-matrix';

interface Row { world: string; origin: string; calling: string; walk: Walk; e: Experience; ms: number }
type Counted = Exclude<keyof Experience, 'keys'>;

export class ExperienceMatrix {
  // One origin a seed, every calling on it.
  static readonly origins: Record<string, string> = { a1: 'order', b2: 'courier', c3: 'wanderer' };
  static readonly columns: [Counted, string][] = [['facets', 'facets'], ['opportunities', 'opps'],
    ['promoted', 'led'], ['buried', 'buried'], ['pursued', 'taken'], ['resolved', 'aims done'],
    ['changing', 'changed'], ['learning', 'learned'], ['acts', 'acts'], ['returns', 'returns'], ['differing', 'differ'],
    ['longest', 'longest'], ['alternations', 'A-B-A-B'], ['heavy', 'heavy'], ['sentences', 'said'],
    ['echoes', 'echoes'], ['revisited', 'back to a bond'], ['kept', 'kept']];
  static async walks(seeds: string[], turns: number, policy: Policy, lab: boolean): Promise<Row[]> {
    const rows: Row[] = [];
    const worlds = [...seeds.map(s => ({ world: s, origin: this.origins[s] ?? 'wanderer' })),
      ...lab ? [{ world: 'laboratory', origin: 'laboratory' }] : []];
    for (const [wi, { world, origin }] of worlds.entries()) {
      for (const [calling, background] of TerminalMatrix.builds) {
        const t0 = performance.now();
        const session = world === 'laboratory'
          ? (await PlayTool.start(PlayTool.parse([Laboratory.file, '--as', `human/${calling}/Wynn/${background}`,
            '--seed', 'a1']))).journey.session
          : await TerminalMatrix.made(world, origin, calling);
        const walk = await RunnerWalk.run(new Runner(session), policy, turns, wi + 1);
        rows.push({ world, origin, calling, walk, e: RunnerExperience.of(walk), ms: performance.now() - t0 });
        console.error(`${world} ${calling} ${origin}: ${Math.round(performance.now() - t0)} ms`);
      }
    }
    return rows;
  }
  static report(rows: Row[], turns: number, policy: Policy): string {
    const head = `| world | calling | ${this.columns.map(c => c[1]).join(' | ')} |`;
    const worlds = [...new Set(rows.map(r => r.world))];
    return ['# The experience measures: a baseline', '',
      `Generated by \`bun scripts/experience-matrix.ts\` (${policy}, ${turns} turns a walk, one origin a seed: `
        + `${worlds.map(w => `${w} ${rows.find(r => r.world === w)!.origin}`).join(', ')}). What each column counts: `
        + '[runner-experience.ts](../../../../src/cli/runner-experience.ts). No thresholds yet.', '',
      '## Each walk', '', head, `|${'---|'.repeat(this.columns.length + 2)}`, ...rows.map(r => this.line(r)), '',
      '## Each round', '', `| world | ${this.columns.map(c => c[1]).join(' | ')} |`,
      `|${'---|'.repeat(this.columns.length + 1)}`,
      ...[...worlds, 'all'].map(w => this.round(w, rows.filter(r => w === 'all' || r.world === w))), '',
      '## Identity: callings paired on one world', '', ...this.identity(rows, worlds), '',
      '## Transcripts', '', ...this.transcripts(rows), ''].join('\n');
  }
  private static line(r: Row): string {
    return `| ${r.world} | ${r.calling} | ${this.columns.map(c => r.e[c[0]]).join(' | ')} |`;
  }
  private static top(rows: Row[], f: (e: Experience) => number): Row {
    return [...rows].sort((a, b) => f(b.e) - f(a.e))[0]!;
  }
  private static round(world: string, rows: Row[]): string {
    return `| ${world} | ${this.columns.map(c => this.mean(rows.map(r => r.e[c[0]]))).join(' | ')} |`;
  }
  private static mean(xs: number[]): string {
    return (xs.reduce((a, b) => a + b, 0) / Math.max(1, xs.length)).toFixed(1);
  }
  // Of each pair of callings on one world, the opportunities one saw and the other did not; and of each calling,
  // those it alone saw.
  private static identity(rows: Row[], worlds: string[]): string[] {
    return worlds.flatMap(w => {
      const on = rows.filter(r => r.world === w), sets = on.map(r => new Set(r.e.keys));
      const pairs = on.flatMap((_, i) => on.slice(i + 1).map((__, j) => {
        const a = sets[i]!, b = sets[i + 1 + j]!;
        return [...a].filter(k => !b.has(k)).length + [...b].filter(k => !a.has(k)).length;
      }));
      const alone = on.map((r, i) => `${r.calling} ${[...sets[i]!].filter(k => sets.every((s, j) => j === i
        || !s.has(k))).length}`);
      return [`- ${w}: pairs differ by ${this.mean(pairs)} opportunities on the mean (least ${Math.min(...pairs)}, `
        + `most ${Math.max(...pairs)}); seen by one calling alone: ${alone.join(', ')}`];
    });
  }
  // The walk that changed the world most, the one that went round most, the one that said most again, and the one
  // that carried an aim longest: its first turns, as the runner said them.
  private static transcripts(rows: Row[]): string[] {
    const picks: [string, Row][] = [['Most changed', this.top(rows, e => e.changing)],
      ['Most gone round', this.top(rows, e => e.alternations)], ['Most said again', this.top(rows, e => e.echoes)],
      ['Longest on one aim', this.top(rows, e => e.longest)]];
    return picks.flatMap(([title, r]) => [`### ${title}: ${r.world} ${r.calling} (${r.origin})`, '',
      ...r.walk.turns.slice(0, 10).map((t, i) => `${i}. ${(t.scene.lines[0] ?? '').slice(0, 110)}`
        + `${t.changed?.length ? ` [changed ${t.changed.length}]` : ''}`
        + `${r.walk.chosen[i] ? ` → ${r.walk.chosen[i]!.label}` : ''}`), '']);
  }
  static async main() {
    const seeds = TerminalMatrix.flag('seeds', 'a1,b2,c3').split(','), turns = Number(TerminalMatrix.flag('turns', '30'));
    const policy = TerminalMatrix.flag('policy', 'curious') as Policy;
    const out = TerminalMatrix.flag('out', 'doc/architecture/mission-21/terminal/experience.md');
    const rows = await this.walks(seeds, turns, policy, !process.argv.includes('--no-lab'));
    await writeFile(out, this.report(rows, turns, policy));
    console.error(`wrote ${out}`);
  }
}
if (import.meta.main) { await ExperienceMatrix.main(); }
