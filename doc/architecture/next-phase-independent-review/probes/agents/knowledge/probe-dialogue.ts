import { PlaySession } from '../../../../../../src/session/play-session';
import { NodeBundleSource } from '../../../../../../src/campaign/node-bundle-source';
import { PlayerView } from '../../../../../../src/presentation/player-view';
import { ModuleWriter } from '../../../../../../src/lang/module-writer';
import { KyrLint } from '../../../../../../src/cli/kyr-lint';
const path = process.argv[2]!;
const lint = await KyrLint.campaign(path, new NodeBundleSource());
console.log('lint errors:', lint.filter((f: any) => f.level === 'error').map((f: any) => f.message));
const s = await PlaySession.start(path, 'p', NodeBundleSource.shared);
const holds = (n: string, ...a: string[]) => s.campaign.world.test(ModuleWriter.call(n, ...a));
const names = () => PlayerView.choices(s.campaign).map(c => `${c.choice.id} :: ${c.choice.name}`);
const pr = (label: string, e: any) => { console.log(`--- ${label}`); for (const p of e.perceptions ?? []) console.log(' ', p.kind, '|', p.id, '|', p.text); if (e.response) console.log('  response:', e.response); };
pr('wait', await s.perform('wait'));
console.log('knows soot_clue (variable obs teaches):', holds('knows', 'party', 'p__soot_clue'));
console.log('knows(ola, murder_fact):', holds('knows', 'p__ola', 'p__murder_fact'));
const ask = PlayerView.choices(s.campaign).find(c => /Ola about the carter/.test(c.choice.name))!;
pr('ask ola', await s.perform(ask.choice.id));
console.log('party knows murder_fact:', holds('knows', 'party', 'p__murder_fact'), 'toldBy:', holds('toldBy', 'party', 'p__ola', 'p__murder_fact'));
console.log('per-member knows? relations named knows over members:', s.campaign.world.related('knows').map(r => r.args.join(',')));
const rec = PlayerView.choices(s.campaign).find(c => /join the company/.test(c.choice.name))!;
pr('recruit', await s.perform(rec.choice.id));
console.log('after recruit able(wil):', holds('able','p__wil'), 'at(wil,_):', s.campaign.world.one('at','p__wil'), 'travelsWith:', holds('travelsWith','p__wil','party'));
console.log('choices w/ Wil:', names().filter(n => /Wil/.test(n)));
// Kill Wil's body
const c: any = s.campaign;
const wilBody = c.readout.creatures.find((x: any) => /Wil/.test(x.name ?? ''));
console.log('wil creature', wilBody?.id, wilBody?.state.hp);
const store = c.creatures; const lease = store.acquire([wilBody.id]); const dead = structuredClone(store.get(wilBody.id)); dead.state.hp = 0;
store.commit(lease, [dead]); store.release(lease);
c.refreshProjection();
console.log('wil readout hp now', c.readout.creatures.find((x: any) => x.id === wilBody?.id)?.state.hp);
console.log('joinedAs:', s.campaign.world.related('joinedAs').map(r => r.args.join(',')), 'awake:', s.campaign.world.related('awake').map(r => r.args.join(',')));
console.log('choices w/ Wil after death:', names().filter(n => /Wil/.test(n)));
const road = PlayerView.choices(s.campaign).find(c => /Wil about the road/.test(c.choice.name));
if (road) pr('ask dead Wil', await s.perform(road.choice.id));
console.log('told log entries:', JSON.stringify(s.campaign.history.slice(-1).map((e: any) => ({ voiced: e.voiced, response: e.response }))).slice(0, 400));
const olaBody = c.readout.creatures.find((x: any) => /Ola/.test(x.name ?? ''));
const l2 = c.creatures.acquire([olaBody.id]); const d2 = structuredClone(c.creatures.get(olaBody.id)); d2.state.hp = 0; c.creatures.commit(l2, [d2]); c.creatures.release(l2); c.refreshProjection();
console.log('able(ola):', holds('able', 'p__ola'), 'dead(ola):', holds('dead', 'p__ola'), 'choices w/ Ola after death:', names().filter(n => /Ola/.test(n)));
