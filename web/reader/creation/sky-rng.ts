// A cheap deterministic stream of numbers in [0, 1), so that the sky is the same every time.
export class SkyRng {
  private s: number;
  constructor(seed: number) { this.s = seed >>> 0; }
  next(): number {
    this.s = (Math.imul(this.s, 1664525) + 1013904223) >>> 0;
    return this.s / 4294967296;
  }
}
