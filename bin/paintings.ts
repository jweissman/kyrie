#!/usr/bin/env bun
// The painting corpus: every image in assets/images (authorized for this project; public-domain and CC0 works), read
// as images, not as file names. For each: its size and digest, what its own metadata says of it (the Web Gallery of
// Art's comment, Art UK's EXIF and IPTC captions, XMP), parsed into artist, title, date, medium and where it hangs; the
// concept it was filed under; and a small copy for the game (web/reader/paintings).
//   bun bin/paintings.ts [dir]     writes data/paintings/registry.json, the copies, and doc/paintings/registry.md
import { createHash } from 'node:crypto';
import { mkdirSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { PaintingMetadata, type Painting } from '../src/paintings/painting-metadata';
import { PaintingConcepts } from '../src/paintings/painting-concepts';

class PaintingsTool {
  static readonly root = resolve(import.meta.dir, '..');
  static async run(dir: string) {
    const files = readdirSync(dir).filter(f => /\.jpe?g$/i.test(f)).sort();
    const out = resolve(this.root, 'web/reader/paintings');
    mkdirSync(out, { recursive: true });
    mkdirSync(resolve(this.root, 'data/paintings'), { recursive: true });
    const entries: Painting[] = [];
    for (const file of files) {
      const bytes = readFileSync(join(dir, file)), id = file.replace(/\.jpe?g$/i, '');
      const meta = PaintingMetadata.read(new Uint8Array(bytes));
      const image = new Bun.Image(bytes.buffer.slice(bytes.byteOffset, bytes.byteOffset + bytes.byteLength));
      const small = await image.resize(320).webp({ quality: 70 }).bytes();
      writeFileSync(join(out, `${id}.webp`), small);
      entries.push({ id, file, bytes: bytes.length, sha1: createHash('sha1').update(bytes).digest('hex'),
        width: meta.width, height: meta.height, ...PaintingMetadata.describe(meta), copy: `paintings/${id}.webp`,
        copyBytes: small.byteLength, concept: PaintingConcepts.of(id) });
    }
    const registry = { about: 'Every painting of the corpus in assets/images, read from the images themselves: what each one\'s own metadata says (source: wga-comment, artuk-exif, iptc, xmp, or none), parsed; the concept it was filed under and what that concept is in the game (concept.kind, concept.family, concept.backgrounds); and the small copy the game shows. Generated by bun bin/paintings.ts; do not edit by hand.',
      count: entries.length, paintings: entries };
    writeFileSync(resolve(this.root, 'data/paintings/registry.json'), `${JSON.stringify(registry, null, 1)}\n`);
    // What the game carries of it: which paintings there are, and how each is credited where it is shown.
    const credits = Object.fromEntries(entries.filter(e => e.artist || e.title)
      .map(e => [e.id, [e.artist, e.title, e.date].filter(Boolean).join(', ')]));
    writeFileSync(resolve(this.root, 'data/paintings/likeness.json'), `${JSON.stringify({ about: 'Generated by bun bin/paintings.ts: the paintings the game can show, by concept, and how each is credited.',
      ids: entries.map(e => e.id), credits }, null, 1)}\n`);
    writeFileSync(resolve(this.root, 'doc/paintings/registry.md'), PaintingConcepts.report(entries));
    console.log(`${entries.length} paintings; ${entries.filter(e => e.artist).length} with an artist; `
      + `${entries.filter(e => e.title).length} with a title; copies ${Math.round(entries.reduce((s, e) => s + e.copyBytes, 0) / 1024)} KiB`);
  }
}

mkdirSync(resolve(PaintingsTool.root, 'doc/paintings'), { recursive: true });
await PaintingsTool.run(resolve(PaintingsTool.root, process.argv[2] ?? 'assets/images'));
