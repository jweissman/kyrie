import type { BundleSource } from '../campaign/bundle-source';
import type { BundleManifest } from '../campaign/module-bundle';
import type { Entry, Placement, ScenarioManifest } from './world-assembler';
import type { Region } from './region-writer';
import { Outfitters } from './outfitters';
import { RegionShops } from './region-shops';
import { RegionTraffic } from './region-traffic';
import { RegionPeoples } from './region-peoples';

// One authority for the names of a country's people, its stories' and its own. The people a story's author named
// (Silkholme's Odile and Garth, Gosse's players) keep their names, and none of the country's own people is given one
// of them (one drawn is drawn again: see Communities.pick): a tin-miner and an armourer called Odile had been the
// folk of a country whose talk was of Odile the silk-gatherer's trouble, in two seeds of twelve (NAV-04). The people
// a story's generation casts (a sick child's mother) are drawn apart from every one of the country's people, its
// shopkeepers and the travellers at its inns among them (see FantasyRules.apart).
export class StoryPeople {
  // A person as Kyr declares one (Kyr.ohm: Person ident string "at" ident), by the name its author gave them.
  static readonly declared = /\bPerson\s+([A-Za-z_]\w*)\s+"((?:[^"\\]|\\.)*)"\s+at\s/g;
  // A scenario of the library, with the names its modules give their people.
  static async entry(base: BundleSource, path: string): Promise<Entry> {
    const manifest = JSON.parse(await base.read(path)) as ScenarioManifest, named = new Set<string>();
    for (const m of manifest.modules) {
      const { texts, cast } = await this.module(base, base.resolve(m.bundle, path));
      for (const text of texts) {
        for (const [, id, name] of text.matchAll(this.declared)) {
          if (!cast.has(id!) && this.proper(name!)) { named.add(name!); }
        }
      }
    }
    return { path, manifest, ...named.size ? { named: [...named] } : {} };
  }
  // The names the stories placed in a country give their people, kept on the country (region.reserved) and said in
  // each placement (named), before any of its own people but its innkeepers, priests, merchants and travellers are
  // named; those, named already, are named again where one has such a name.
  static reserve(region: Region, placements: Placement[], library: Entry[]): void {
    const reserved = new Set<string>();
    for (const p of placements) {
      const named = library.find(e => e.manifest.id === p.scenario)?.named ?? [];
      if (named.length) { p.named = named; }
      for (const n of named) { reserved.add(n); }
    }
    region.reserved = [...reserved];
    RegionPeoples.apart(region, region.reserved);
  }
  // Every name the country's people have, which a story's generated people are drawn apart from: its settled folk and
  // chandlers, its shopkeepers, the travellers on its roads, who spend their nights at its inns, and its stories'.
  static country(region: Region): string[] {
    const settled = Outfitters.everyone(region), reserved = region.reserved ?? [];
    return [...new Set([...settled, ...RegionShops.keepers(region), ...RegionTraffic.names(region), ...reserved])];
  }
  // Someone with a name of their own ("Odile", "Absalom Gosse"), not what they are ("the brood-mother", "The sick
  // child's mother", whom generation names).
  private static proper(name: string): boolean { return name.split(' ').every(w => /^\p{Lu}/u.test(w)); }
  // A module's sources, and the people its generation casts (the tower's necromancer, declared "Someone"), whom
  // generation names and not their author: the keys of the templates its casting is generated by.
  private static async module(base: BundleSource, path: string): Promise<{ texts: string[]; cast: Set<string> }> {
    const manifest = JSON.parse(await base.read(path)) as BundleManifest, cast = new Set<string>();
    const files = Array.isArray(manifest.source) ? manifest.source : [manifest.source];
    const texts = await Promise.all(files.map(f => base.read(base.resolve(f, path))));
    const g = manifest.generation;
    if (g?.templates) {
      const templates = JSON.parse(await base.read(base.resolve(g.templates, path))) as Record<string, unknown>;
      const casting = String((templates[g.type] as { casting?: unknown } | undefined)?.casting ?? '');
      for (const [, t] of casting.matchAll(/gen\((\w+)\)/g)) {
        for (const id of Object.keys(templates[t!] ?? {}).filter(k => !k.startsWith('_'))) { cast.add(id); }
      }
    }
    return { texts, cast };
  }
}
