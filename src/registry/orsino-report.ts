import { OrsinoRegistry } from './orsino-registry';

// The compatibility matrix as Markdown, rendered only from the registry snapshot, the support table and the ledger,
// so that the committed report can be regenerated and compared.
export class OrsinoReport {
  static render(registry: OrsinoRegistry): string {
    const s = registry.snapshot;
    const rows = registry.coverage()
      .sort((a, b) => a.concept.localeCompare(b.concept) || a.family.localeCompare(b.family));
    const totals = Object.fromEntries((['feasible', 'represented', 'executable', 'play-validated'] as const)
      .map(k => [k, rows.reduce((n, r) => n + r[k], 0)]));
    const unresolved = s.entries.flatMap(e => e.references.filter(r => !r.resolved).map(r => ({ id: e.id, ...r })));
    const byRef = new Map<string, string[]>();
    for (const u of unresolved) { (byRef.get(u.ref) ?? byRef.set(u.ref, []).get(u.ref)!).push(u.id); }
    const lines = [
      '# Orsino registry: coverage and compatibility matrix', '',
      'Generated by `bun bin/orsino-registry.ts report` from `data/sources/orsino/registry.json` (Orsino revision',
      `\`${s.source.revision}\`), \`data/sources/orsino/kyr-support.json\` and \`data/sources/orsino/adaptations.json\`. Do not edit by hand.`, '',
      'Support levels: **catalogued** (source preserved in the registry), **represented** (typed Kyr equivalent, some',
      'mechanics omitted), **executable** (every source mechanic runs through canonical Kyr systems or has a declared',
      'adaptation), **play-validated** (exercised in recorded play). *Feasible* counts entries whose every rule feature',
      'Kyr can already execute (faithfully or by documented adaptation); it is not a claim that a Kyr definition exists.', '',
      `${s.entries.length} entries in ${rows.length} families.`
        + ` ${totals.represented! + totals.executable! + totals['play-validated']!} represented or better;`
        + ` ${totals.executable! + totals['play-validated']!} executable or better;`
        + ` ${totals['play-validated']!} play-validated; ${totals.feasible!} feasible.`, '',
      '## By family', '',
      '| Concept | Family | Entries | Represented | Executable | Play-validated | Feasible |',
      '|---|---|---:|---:|---:|---:|---:|',
      ...rows.map(r => `| ${r.concept} | ${r.family} | ${r.total} | ${r.represented} | ${r.executable} | ${r['play-validated']} | ${r.feasible} |`),
      '', '## Largest mechanical gaps', '',
      'Unsupported rule features ranked by how many character, magic, condition, equipment and creature entries use',
      'them. *Sole* counts entries for which this is the only missing feature.', '',
      '| Feature | Entries | Sole | Families |', '|---|---:|---:|---|',
      ...registry.gaps().slice(0, 60).map(g => `| \`${g.feature}\` | ${g.entries} | ${g.sole} | ${g.families.join(', ')} |`),
      '', '## Source inconsistencies', '',
      'References in the Orsino source that name nothing in the corpus. They are preserved, not repaired.', '',
      '| Missing reference | Referenced by |', '|---|---|',
      ...[...byRef].sort(([a], [b]) => a.localeCompare(b)).map(([ref, ids]) => `| \`${ref}\` | ${ids.join(', ')} |`),
      '', 'Definitions shadowed at Orsino load time (abilities.json, then abilities/*.json; later keys win):', '',
      ...s.entries.filter(e => e.shadowedBy).map(e => `- \`${e.id}\` is replaced by \`${e.shadowedBy!}\``),
      '', '## Adaptation records', '',
      '| Orsino entry | Kyr definitions | Support | Fidelity | Note |', '|---|---|---|---|---|',
      ...registry.ledger.records.map(r => `| \`${r.orsino}\` | ${r.kyr.map(k => `\`${k}\``).join(' ')} | ${r.support} | ${r.fidelity} | ${r.note} |`),
      '',
    ];
    return lines.join('\n');
  }
}
