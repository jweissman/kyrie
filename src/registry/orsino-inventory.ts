import destinations from '../../data/sources/orsino/destinations.json';
import world from '../../data/generation/scenes/orsino-world.json';
import snares from '../../data/generation/scenes/snares.json';
import weather from '../../data/generation/tables/weather.json';
import combat from '../../data/voice/combat.json';
import met from '../../data/generation/scenes/wonders.json';
import { RegionMarvels } from '../world/region-marvels';
import { RegionShops } from '../world/region-shops';
import { OrsinoRegistry, type Support } from './orsino-registry';
import type { RegistryEntry } from './orsino-extract';

export type Placement = 'integrated' | 'represented' | 'reference' | 'blocked';
export interface Destination {
  destination: string; representation: string; generative: string; tests: string[]; status: Placement;
  blocker?: string; rule: 'ledger' | 'wonder' | 'trap' | 'mechanism' | 'bark' | 'climate' | 'riddle' | 'shop' | 'family';
}
// One Orsino entry: where it is in Kyr (by its family, and the Kyr definitions that name it), how far its mechanics
// run, and, unless it is met in play, exactly what stands in the way.
export interface InventoryRow {
  id: string; status: Placement; mechanics?: Support; kyr?: string[]; blockers?: string[];
}
export interface Inventory {
  about: string; revision: string;
  families: Record<string, Destination & { concept: string; counts: Record<Placement, number> }>;
  entries: InventoryRow[];
}

// The source-to-destination inventory of Orsino's corpus (data/sources/orsino/inventory.json): every registry entry,
// with its family's destination (data/sources/orsino/destinations.json) and its own status, computed from what Kyr
// has and draws, never claimed: the adaptation ledger and generated catalogs for rules and things; what a generated
// country draws for wonders and traps; the voice tables for barks.
export class OrsinoInventory {
  static readonly placements: Placement[] = ['integrated', 'represented', 'reference', 'blocked'];
  static readonly families = destinations.families as Record<string, Destination>;
  constructor(private readonly registry: OrsinoRegistry) {}
  build(): Inventory {
    const entries = this.registry.snapshot.entries.map(e => this.row(e));
    const families = Object.fromEntries(Object.entries(this.registry.snapshot.families).map(([family, f]) => {
      const counts = Object.fromEntries(OrsinoInventory.placements.map(p => [p,
        entries.filter(r => r.status === p && r.id.startsWith(`${family}:`)).length])) as Record<Placement, number>;
      return [family, { concept: f.concept, ...OrsinoInventory.families[family]!, counts }];
    }));
    return { about: 'Generated by bun bin/orsino-registry.ts inventory from the registry, the ledger and'
      + ' data/sources/orsino/destinations.json; do not edit.', revision: this.registry.snapshot.source.revision,
    families, entries };
  }
  row(e: RegistryEntry): InventoryRow {
    const family = OrsinoInventory.families[e.family];
    if (!family) { return { id: e.id, status: 'blocked', blockers: [`The family ${e.family} has no destination decided.`] }; }
    const own = this.own(e, family);
    const status = own?.status ?? family.status;
    const blockers = own ? own.blockers : status === 'integrated' ? [] : [family.blocker ?? 'No blocker given.'];
    const mechanics = OrsinoRegistry.mechanical.has(e.concept) ? this.registry.status(e.id) : undefined;
    const kyr = this.registry.adaptations(e.id).flatMap(r => r.kyr);
    return { id: e.id, status, ...mechanics ? { mechanics } : {}, ...kyr.length ? { kyr } : {},
      ...blockers.length ? { blockers } : {} };
  }
  // An entry's own status, where it can be read off what Kyr has.
  private own(e: RegistryEntry, family: Destination): { status: Placement; blockers: string[] } | undefined {
    switch (family.rule) {
      case 'ledger': return this.ledger(e);
      case 'wonder': return this.wonder(e.key);
      case 'trap': return this.trap(e.key);
      case 'mechanism': return this.drawn(e.key.replace(/_/g, ' ') in snares.mechanisms,
        'No way of seeing and dealing with it is written in data/generation/scenes/snares.json.');
      case 'bark': return this.drawn(OrsinoInventory.barks.some(b => b.startsWith(`barks:${this.bark(e)}`)),
        'No row of data/voice/combat.json carries it.');
      case 'climate': return this.drawn(e.key in weather.climateWeather.groups,
        'Not among the climates of data/generation/tables/weather.json.');
      case 'shop': return this.drawn(e.key in RegionShops.kinds && (RegionShops.stocks[e.key]?.stock.length ?? 0) >= 3,
        (RegionShops.stocks[e.key]?.stock.length ?? 0) < 3 ? 'Kyr has fewer than three things of its kinds a country\'s market'
          + ' sees (worth 300 coin or less): nothing for such a shop to stock.' : 'No town keeps one (src/world/region-shops.ts).');
      case 'riddle': return this.drawn(e.family === 'riddle' ? !!(world.riddles as Record<string, unknown[]>)[e.key]?.length
        : e.key in (world as unknown as { riddleAnswers: Record<string, string[]> }).riddleAnswers,
      'Not plain words a door can offer (data/generation/scenes/orsino-world.json#riddleAnswers).');
      default: return undefined;
    }
  }
  private drawn(yes: boolean, blocker: string) {
    return yes ? { status: 'integrated' as const, blockers: [] } : { status: 'blocked' as const, blockers: [blocker] };
  }
  private ledger(e: RegistryEntry): { status: Placement; blockers: string[] } {
    const support = this.registry.status(e.id), records = this.registry.adaptations(e.id);
    if (support === 'executable' || support === 'play-validated') { return { status: 'integrated', blockers: [] }; }
    if (support === 'represented') {
      const omitted = records.flatMap(r => Object.entries(r.omits ?? {}).map(([f, why]) => `${f}: ${why}`));
      return { status: 'represented', blockers: omitted.length ? omitted : records.map(r => r.note) };
    }
    const unsupported = this.registry.blockers(e).map(f => `${f}: ${OrsinoRegistry.judge(f).note || 'not supported'}`);
    return { status: 'blocked', blockers: unsupported.length ? unsupported
      : ['Every feature it uses runs in Kyr, but no Kyr definition translates it yet.'] };
  }
  private wonder(key: string): { status: Placement; blockers: string[] } {
    if (RegionMarvels.wonders.some(([k]) => k === key)) { return { status: 'integrated', blockers: [] }; }
    const w = (world.wonders as Record<string, { effect?: string; omits?: Record<string, string> }>)[key];
    if (w?.effect && !(key in met.wonders)) { return { status: 'blocked', blockers: ['No meeting is written for it in data/generation/scenes/wonders.json.'] }; }
    return { status: 'blocked', blockers: Object.entries(w?.omits ?? {}).map(([k, why]) => `${k}: ${why}`) };
  }
  private trap(key: string): { status: Placement; blockers: string[] } {
    if (RegionMarvels.traps.some(([k]) => k === key)) { return { status: 'integrated', blockers: [] }; }
    const t = (world.traps as Record<string, { effect?: string; omits?: Record<string, string> }>)[key];
    if (t?.effect) {
      return { status: 'blocked', blockers: [`Does ${RegionMarvels.harm(t.effect)} harm on an average roll: more than`
        + ' a generated work\'s trap may (10.5, three dice of six).'] };
    }
    return { status: 'blocked', blockers: Object.entries(t?.omits ?? {}).map(([k, why]) => `${k}: ${why}`) };
  }
  // A bark entry's key among the voice rows' sources: generic.onFall, npc.Acolyte, personality.acerbic.
  private bark(e: RegistryEntry): string {
    return `${{ eventBark: 'generic', npcBark: 'npc', personalityBark: 'personality' }[e.family]}.${e.key}`;
  }
  private static readonly barks = (combat.lines as { source?: { orsino?: string } }[])
    .flatMap(l => l.source?.orsino ? [l.source.orsino] : []);
}
