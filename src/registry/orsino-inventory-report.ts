import { OrsinoInventory, type Inventory } from './orsino-inventory';

// The inventory as Markdown (doc/architecture/orsino-inventory.md): a family table, then each family that is not
// wholly met in play with what stands in its way, the commonest blocker first.
export class OrsinoInventoryReport {
  static render(inventory: Inventory): string {
    const families = Object.entries(inventory.families)
      .sort(([a, x], [b, y]) => x.concept.localeCompare(y.concept) || a.localeCompare(b));
    const total = Object.fromEntries(OrsinoInventory.placements.map(p =>
      [p, inventory.entries.filter(e => e.status === p).length]));
    return [
      '# Orsino inventory: where everything went', '',
      'Generated by `bun bin/orsino-registry.ts inventory` from `data/sources/orsino/registry.json` (Orsino revision',
      `\`${inventory.revision}\`), the adaptation ledger and \`data/sources/orsino/destinations.json\`. The`,
      'machine-readable inventory is `data/sources/orsino/inventory.json`. Do not edit by hand.', '',
      'Statuses: **integrated** (in Kyr and met in play), **represented** (in Kyr\'s data, but play does not reach it, or',
      'reaches it with declared omissions), **reference** (kept in the registry only, because Kyr does this another way),',
      '**blocked** (Kyr would carry it, but cannot yet; the blocker says exactly what is missing). An entry\'s status is',
      'computed from what Kyr has and draws, not claimed: the ledger and generated catalogs for rules and things, what',
      'a generated country draws for wonders and traps, the voice tables for barks.', '',
      `${inventory.entries.length} entries in ${families.length} families: ${total.integrated} integrated,`
        + ` ${total.represented} represented, ${total.reference} reference, ${total.blocked} blocked.`, '',
      '## By family', '',
      '| Concept | Family | Entries | Integrated | Represented | Reference | Blocked | Destination | Generation '
        + '| Tests |',
      '|---|---|---:|---:|---:|---:|---:|---|---|---|',
      ...families.map(([name, f]) => `| ${f.concept} | ${name} | ${this.sum(f.counts)} | ${f.counts.integrated}`
        + ` | ${f.counts.represented} | ${f.counts.reference} | ${f.counts.blocked} | ${f.destination}`
        + ` | ${f.generative} | ${f.tests.map(t => `\`${t}\``).join(' ') || '—'} |`),
      '', '## What stands in the way', '',
      'For each family with entries not met in play: its blockers, with how many entries each holds back.', '',
      ...families.flatMap(([name]) => this.blockers(inventory, name)), '',
    ].join('\n');
  }
  private static sum(counts: Record<string, number>): number {
    return Object.values(counts).reduce((a, b) => a + b, 0);
  }
  private static blockers(inventory: Inventory, family: string): string[] {
    const rows = inventory.entries.filter(e => e.id.startsWith(`${family}:`) && e.status !== 'integrated');
    if (!rows.length) { return []; }
    const counts = new Map<string, number>();
    for (const b of rows.flatMap(r => [...new Set(r.blockers ?? [])])) { counts.set(b, (counts.get(b) ?? 0) + 1); }
    const listed = [...counts].sort((a, b) => b[1] - a[1] || a[0].localeCompare(b[0]));
    return [`### ${family}`, '', ...listed.slice(0, 12).map(([b, n]) => `- ${n} × ${b.replace(/\|/g, '\\|')}`),
      ...listed.length > 12 ? [`- and ${listed.length - 12} more, each in inventory.json`] : [], ''];
  }
}
