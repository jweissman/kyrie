import abilities from '../../data/catalog/orsino/abilities.json';
import conditions from '../../data/catalog/orsino/conditions.json';
import items from '../../data/catalog/orsino/items.json';
import traits from '../../data/catalog/orsino/traits.json';
import blessings from '../../data/catalog/orsino/blessings.json';
import species from '../../data/catalog/orsino/species.json';
import variants from '../../data/catalog/orsino/variants.json';
import type { AdaptationRecord, Ledger } from './orsino-registry';
import { Canon } from '../canon/canon';

interface Generated {
  source?: { orsino?: string; fidelity?: 'faithful' | 'adapted' }; unsupported?: object; omits?: Record<string, string>;
}

// Adaptation records for the generated Orsino catalogs, derived rather than written: an entry is executable unless its
// translation recorded something Kyr cannot execute, in which case it is only represented. Hand-written ledger
// records (play validation with evidence, Kyr's own adaptations) take precedence for the same Orsino entry.
export class CatalogLedger {
  private static readonly families: [string, Record<string, Generated>][] = [
    ['ability', abilities.abilities as Record<string, Generated>],
    ['condition', conditions.conditions as Record<string, Generated>],
    ['item', items.items as Record<string, Generated>],
    ['trait', traits.traits as Record<string, Generated>],
    ['domain', blessings.blessings as Record<string, Generated>],
    ['species', species.species as unknown as Record<string, Generated>],
  ];
  static records(): AdaptationRecord[] {
    // Backgrounds are compiled from Orsino's rows and Kyr's kind tables at load; the compiled catalog is the record.
    const families = [...this.families, ['background', Canon.backgrounds as Record<string, Generated>] as const];
    return families.flatMap(([family, entries]) => Object.entries(entries).flatMap(([id, e]) => {
      const orsino = e.source?.orsino;
      if (!orsino) { return []; }
      const gaps = Object.keys(e.unsupported ?? {});
      return [{ orsino, kyr: [`${family}:${id}`], support: gaps.length ? 'represented' as const : 'executable' as const,
        fidelity: e.source?.fidelity ?? (Object.keys(e.omits ?? {}).length ? 'adapted' : 'faithful'),
        note: gaps.length ? `Generated; not executable: ${gaps.join(', ')}.` : 'Generated by the Orsino translator.',
        ...e.omits ? { omits: Object.fromEntries(Object.entries(e.omits)
          .map(([k, v]) => [k.includes(':') ? k : `modifier:${k}`, v])) } : {},
        generated: true as const }];
    }));
  }
  // Creature aspects and undead templates (data/catalog/orsino/variants.json): applied as written, but an aspect is
  // drawn for a den when its country is made, not at each meeting; and the rarities they are drawn by.
  static variants(): AdaptationRecord[] {
    const table = variants as unknown as { aspects: Record<string, { source: string }>;
      templates: Record<string, { source: string }>; rarity: Record<string, string[]> };
    return [...Object.entries(table.aspects).map(([id, v]) => this.record(v.source, `aspect:${id}`, 'adapted',
      'Its attributes and abilities applied to the creature; drawn by rarity for a den when the country is made.')),
    ...Object.entries(table.templates).map(([id, v]) => this.record(v.source, `undead:${id}`, 'faithful',
      'Its attributes, traits and abilities applied to the creature (Undead in Kyr), and its den laid to rest by rites.')),
    ...Object.keys(table.rarity).map(id => this.record(`aspectRarity:${id}`, `rarity:${id}`, 'faithful',
      'The aspects of this rarity, drawn with the weights in CreatureVariants.'))];
  }
  private static record(orsino: string, kyr: string, fidelity: 'faithful' | 'adapted', note: string): AdaptationRecord {
    return { orsino, kyr: [kyr], support: 'executable', fidelity, note, generated: true };
  }
  static combined(ledger: Ledger): Ledger {
    const written = new Set(ledger.records.flatMap(r => r.kyr.map(k => `${r.orsino} ${k}`)));
    return { ...ledger, records: [...ledger.records,
      ...[...this.records(), ...this.variants()].filter(r => !written.has(`${r.orsino} ${r.kyr[0]!}`))] };
  }
}
