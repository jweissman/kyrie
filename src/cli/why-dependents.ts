import { Glob } from 'bun';
import { existsSync, readFileSync } from 'node:fs';
import { join } from 'node:path';
import type { Change, Module } from '../lang/module';
import { NodeBundleSource } from '../campaign/node-bundle-source';
import type { BundleManifest } from '../campaign/module-bundle';
import { ModuleExports } from '../campaign/module-exports';
import { WhySources, type SourceLine } from './why-sources';
import { WhyWriter } from './why-writer';

// One thing a module's Kyr does with a symbol: its kind (an act, a rule, a pursuit, an observation, an aim), its id,
// and whether it reads it (asks it in a condition) or changes it (a change naming it: asserts, retracts or sets it,
// moves it, or teaches it).
interface Use { kind: string; id: string; writes: boolean }

// `kyrie inspect --dependents`: what depends on a symbol (the platform maturity study's §7.1, the fourth of its
// questions; the maturity track's step 4): where it is declared (and, for a drawn world's generated line, the
// template that wrote it), every module that imports it as another name, every act, rule, pursuit, observation and
// aim that reads or writes it, each at its declaration, and the tests and presenters of the repository that name it.
// Read from the campaign as it is loaded, as `--why` reads it; nothing is played.
//   bin/kyrie inspect --dependents <campaign.json> | --world <seed> <symbol>
export class WhyDependents {
  // The ids a symbol names: itself, or a module's own of that name (mob: walk__mob), entities, relations, measures,
  // queries, acts and rules alike.
  static resolved(module: Module, symbol: string): string[] {
    const all = new Set([...module.entities.map(e => e.id), ...module.relations.map(r => r.name),
      ...module.measures.map(m => m.name), ...module.queries.map(q => q.name), ...module.actions.map(a => a.id),
      ...(module.rules ?? []).map(r => r.id)]);
    return all.has(symbol) ? [symbol] : [...all].filter(id => id.endsWith(`__${symbol}`)).sort();
  }
  static async report(module: Module, sources: WhySources | undefined, symbol: string): Promise<string[]> {
    const ids = this.resolved(module, symbol);
    if (!ids.length) { return [`Nothing in the campaign is called ${symbol}.`]; }
    const out: string[] = [];
    for (const id of ids) { out.push(...await this.one(module, sources, id)); }
    return out;
  }
  private static async one(module: Module, sources: WhySources | undefined, id: string): Promise<string[]> {
    const declared = await sources?.declared(id);
    const out = [`${id}: ${declared ? this.at(declared) : 'declared nowhere the campaign was read from'}`];
    out.push(...(await this.imports(sources, id)).map(l => `  imported: ${l}`));
    const uses = this.uses(module, id);
    for (const writes of [false, true]) {
      const these = uses.filter(u => u.writes === writes);
      if (!these.length) { continue; }
      out.push(`  ${writes ? 'changed' : 'read'} by ${these.length}:`);
      for (const u of these) {
        // (A topic's "again", which its once made, by the topic.)
        const l = await sources?.declared(u.id, this.keywords[u.kind])
          ?? await sources?.declared(u.id.replace(/_again$/, ''), this.keywords[u.kind]);
        out.push(`    ${u.kind} ${u.id}${l ? ` at ${this.at(l)}` : ''}`);
      }
    }
    for (const [what, dirs] of [['tests', ['test']], ['presenters', ['src/presentation', 'src/ui', 'src/cli']]] as const) {
      const files = this.naming(id, dirs);
      if (files.length) { out.push(`  ${what} naming it (${files.length}): ${files.slice(0, 8).join(', ')}${files.length > 8 ? ', …' : ''}`); }
    }
    return out;
  }
  static readonly keywords: Record<string, string> = { act: 'Action|Topic|Event', rule: 'Rule|Event',
    pursuit: 'Pursuit|Route', observation: 'Observe', aim: 'Objective' };
  // A line as `--why` says one, with the generator's template for a line of a world's own generated Kyr.
  private static at(l: SourceLine): string {
    const generated = existsSync(join(NodeBundleSource.root, l.file)) ? [] : WhyWriter.of(l.text);
    return [WhySources.said(l, 90), ...generated].join('; generated by ');
  }
  // Every act, rule, pursuit, observation and aim that names the id, and whether it writes it.
  static uses(module: Module, id: string): Use[] {
    const n = this.named.bind(this, id);
    return [
      ...module.actions.filter(n).map(a => ({ kind: 'act', id: a.schema ?? a.id,
        writes: this.writes(id, [...a.success, ...a.failure]) })),
      ...(module.rules ?? []).filter(n).map(r => ({ kind: 'rule', id: r.id, writes: this.writes(id, r.effects) })),
      ...(module.pursuits ?? []).filter(n).map(p => ({ kind: 'pursuit', id: p.id, writes: n(p.target) })),
      ...(module.observations ?? []).filter(n).map(o => ({ kind: 'observation', id: o.id, writes: false })),
      ...(module.objectives ?? []).filter(n).map(o => ({ kind: 'aim', id: o.id, writes: false })),
    ].filter((u, i, all) => all.findIndex(v => v.kind === u.kind && v.id === u.id) === i);
  }
  private static named(id: string, x: unknown): boolean { return (JSON.stringify(x) ?? '').includes(`"${id}"`); }
  private static writes(id: string, changes: Change[]): boolean {
    return changes.some(c => 'call' in c && this.named(id, c.call));
  }
  // The modules that import the id as a name of their own (a request's `imports`, its name to "module.export"), by the
  // campaign's manifest and the exporting module's exports.
  private static async imports(sources: WhySources | undefined, id: string): Promise<string[]> {
    const requests = sources ? (await sources.manifest()).modules : [], out: string[] = [];
    for (const r of requests) {
      for (const [local, ref] of Object.entries(r.imports ?? {})) {
        const [from, name] = ref.split('.'), exporter = requests.find(x => x.id === from);
        if (!exporter || !name) { continue; }
        const manifest = JSON.parse(await sources!.source.read(exporter.bundle)) as BundleManifest;
        if (`${from}__${ModuleExports.locals(manifest.exports)[name]}` === id) { out.push(`${r.id}'s ${local} (${ref})`); }
      }
    }
    return out;
  }
  // The repository's files under the directories that name the id outright.
  private static naming(id: string, dirs: readonly string[]): string[] {
    const root = NodeBundleSource.root;
    return dirs.flatMap(d => [...new Glob(`${d}/**/*.ts`).scanSync(root)])
      .filter(f => f !== 'src/cli/why-dependents.ts' && readFileSync(join(root, f), 'utf8').includes(id)).sort();
  }
}
