import { Canon } from '../canon/canon';
import { CreatureFidelity, creatureFields } from './srd-creature-fidelity';
import { SpellFidelity, spellFields } from './srd-spell-fidelity';
import type { Cell, CreatureRow } from './srd-creature-fidelity';
import type { Encounters } from './srd-encounters';
import type { Field, SpellRow } from './srd-spell-fidelity';

// The fidelity census as doc/architecture/mission-21/rules/srd-fidelity.md (scripts/srd-fidelity.ts writes it;
// test/srd-fidelity holds it current): the headline that can rise, then every creature with an SRD counterpart by
// how often a player meets it, then every spell with one.
export class SrdFidelityReport {
  static headline(e: Encounters): { encounters: [number, number, number]; met: [number, number, number];
    spells: [number, number, number, number] } {
    const rows = new Map(CreatureFidelity.rows().map(r => [r.id, r]));
    const a1 = e.a1.filter(g => g.kinds.every(k => !k.startsWith('person:')));
    const met = Object.entries(e.dens).filter(([k]) => !k.startsWith('person:'));
    const total = met.reduce((s, [, n]) => s + n, 0);
    const spells = SpellFidelity.rows(), all = Object.values(Canon.abilities).filter(a => a.spell).length;
    return { encounters: [a1.filter(g => g.kinds.every(k => this.faithful(rows, k))).length,
      a1.filter(g => g.kinds.every(k => rows.has(k))).length, a1.length],
    met: [met.filter(([k]) => this.faithful(rows, k)).reduce((s, [, n]) => s + n, 0),
      met.filter(([k]) => rows.has(k)).reduce((s, [, n]) => s + n, 0), total],
    spells: [spells.filter(r => SpellFidelity.faithful(r)).length, spells.length, all,
      spells.filter(r => SpellFidelity.faithful(r, spellFields)).length] };
  }
  private static faithful(rows: Map<string, CreatureRow>, kind: string): boolean {
    return !!rows.get(kind) && CreatureFidelity.faithful(rows.get(kind)!);
  }
  private static pct(n: number, d: number): string { return `${Math.round(100 * n / d)} %`; }
  static markdown(e: Encounters): string {
    const h = this.headline(e), pct = this.pct.bind(this);
    return ['# SRD fidelity (Mission 21, rules)', '',
      'Generated by `bun scripts/srd-fidelity.ts` from the catalog, the Revised 3.5 SRD reference values and the',
      'concordance (data/sources/srd35); test/srd-fidelity holds it current. Do not edit by hand.', '',
      `**${h.encounters[0]} of ${h.encounters[2]} placed encounters in a1 SRD-faithful** (a hostile group whose every`,
      `kind is exact in all six fields); ${h.encounters[1]} of them have an SRD counterpart for every kind. **Spells`,
      `${h.spells[0]} of ${h.spells[1]}** with an SRD counterpart faithful in level, school, harm and save (of`,
      `${h.spells[2]} catalog spells); ${h.spells[3]} in all seven fields, their reach and duration too.`,
      '', `In six generated countries' dens (${e.countries.join(', ')}), ${pct(h.met[1], h.met[2])} of meetings are with a`,
      `kind that has an SRD counterpart and ${pct(h.met[0], h.met[2])} with a faithful one (${h.met[2]} groups).`, '',
      ...this.fieldCounts(), '', '## Creatures, most met first', '',
      'Met: groups in a1 / groups in the six countries\' dens. ✓ exact; ✗ ours → the SRD\'s; O Orsino\'s own, no SRD',
      'value taken; E the SRD\'s needs what the engine lacks; ≈ converted by a named rule; – neither has one.', '',
      `| kind | SRD | met | ${creatureFields.join(' | ')} |`, `|${' --- |'.repeat(creatureFields.length + 3)}`,
      ...this.creatures(e), '', '## Spells', '', `| spell | SRD | ${spellFields.join(' | ')} |`,
      `|${' --- |'.repeat(spellFields.length + 2)}`, ...SpellFidelity.rows().map(r => this.spellLine(r)), ''].join('\n');
  }
  private static fieldCounts(): string[] {
    const creatures = CreatureFidelity.rows(), spells = SpellFidelity.rows();
    return ['| creatures, field exact or converted | ' + creatureFields.map(f => `${f} ${this.count(creatures
      .map(r => r[f]))}`).join(' | ') + ` | of ${creatures.length} |`, '| --- |' + ' --- |'.repeat(creatureFields.length + 1),
    '| spells, field exact or converted | ' + spellFields.map(f => `${f} ${this.count(spells.map(r => r[f]))}`).join(' | ')
      + ` | of ${spells.length} |`];
  }
  private static count(cells: (Cell | Field)[]): number {
    return cells.filter(c => ['exact', 'converted'].includes(c.verdict)).length;
  }
  private static creatures(e: Encounters): string[] {
    return CreatureFidelity.rows().map(r => ({ r, a1: e.a1.filter(g => g.kinds.includes(r.id)).length,
      dens: e.dens[r.id] ?? 0 }))
      .sort((a, b) => b.a1 + b.dens - a.a1 - a.dens || a.r.id.localeCompare(b.r.id))
      .map(({ r, a1, dens }) => `| ${r.id} | ${r.srd} | ${a1}/${dens} | ${creatureFields.map(f => this.cell(r[f])).join(' | ')} |`);
  }
  private static cell(c: Cell | Field): string {
    const v = { exact: '✓', 'n/a': '–', orsino: 'O', engine: 'E', differs: '✗', converted: '≈' }[c.verdict];
    return c.verdict === 'differs' ? `✗ ${c.ours || '·'} → ${c.theirs || '·'}` : c.verdict === 'engine' ? `E ${c.theirs}`
      : c.verdict === 'converted' ? `≈ ${c.ours}` : v;
  }
  private static spellLine(r: SpellRow): string {
    return `| ${r.id} | ${r.srd} | ${spellFields.map(f => this.cell(r[f])).join(' | ')} |`;
  }
  static rowsOf(): CreatureRow[] { return CreatureFidelity.rows(); }
}
