import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import animals from '../../data/catalog/animals.json';
import monsters from '../../data/catalog/monsters.json';
import { Content } from '../content';
import { CombatProjection } from '../combat-projection';
import { Battle } from '../battle';
import { Tactics } from '../tactics';
import { CreatureVariants } from '../creature-variants';
import type { Fighter } from '../model';

// The bestiary's tools: `challenge` measures how dangerous each kind is (data/catalog/challenge.json), by fighting it
// with the game's own fights against a lone human warrior of the standard kit: the level of warrior that wins half the
// time against one of the kind (a kind beaten so easily that several are needed, the share of a first-level warrior it
// is). Run it after a creature, a variation or the fights change; `test/bestiary.test.ts` says when a kind is
// unmeasured.
export class BestiaryTool {
  static readonly trials = 12;
  static readonly levels = [1, 2, 3, 4, 5, 6, 8, 10, 12, 14, 16, 18, 20];
  static readonly packs = [2, 3, 4, 6, 8];
  static async main(args: string[]): Promise<number> {
    if (args[0] === 'report') {
      const { BestiaryReport } = await import('./bestiary-report');
      return BestiaryReport.main(args.length > 1 ? args.slice(1) : ['a1', 'b2', 'kite', 'ash', 'wren', 'mere', 'thorn', 'cov2']);
    }
    if (args[0] !== 'challenge') {
      console.log('bin/kyrie bestiary challenge [kind ...]: measure each kind into data/catalog/challenge.json\n'
        + 'bin/kyrie bestiary report [seed ...]: what of the bestiary generated countries meet, and what can reach it');
      return 1;
    }
    const kinds = args.length > 1 ? args.slice(1) : this.measurable();
    const file = 'data/catalog/challenge.json';
    const kept = (existsSync(file) ? JSON.parse(readFileSync(file, 'utf8')) : { kinds: {} }) as
      { kinds: Record<string, [number, number]> };
    for (const kind of kinds) {
      kept.kinds[kind] = [this.challenge(kind, 1), this.challenge(kind, 5)];
      console.log(kind, kept.kinds[kind]!.join(' '));
    }
    const sorted = Object.fromEntries(Object.entries(kept.kinds).sort(([a], [b]) => a.localeCompare(b)));
    writeFileSync(file, `${JSON.stringify({ about: 'Generated by bin/kyrie bestiary challenge; '
      + 'do not edit. Each kind\'s challenge at its first level and its fifth: the level of a lone human warrior who wins '
      + 'half the time against one of it, or the share of a first-level warrior one is where several are needed '
      + '(see src/world/challenge.ts).', kinds: sorted }, null, 1)}\n`);
    return 0;
  }
  // Every creature of the catalog's own files that fights: not a device, nor a kind only ever met with what it requires
  // (an elemental's element); not a module's own kinds, installed as it loads.
  static measurable(): string[] {
    return Object.keys({ ...animals.species, ...monsters.species }).filter(id => !CreatureVariants.wanting(id));
  }
  private static readonly content = new Content('bestiary');
  // The challenge of one of a kind at a level.
  static challenge(kind: string, level: number): number {
    if (this.won(kind, level, { warrior: 1, foes: 1 }) >= 0.5) {
      const many = this.packs.filter(n => this.won(kind, level, { warrior: 1, foes: n }) >= 0.5).at(-1);
      return many ? Math.round(100 / many) / 100 : 1;
    }
    return this.levels.find(l => this.won(kind, level, { warrior: l, foes: 1 }) >= 0.5) ?? 24;
  }
  // How often a warrior of a level beats so many of the kind.
  static won(kind: string, level: number, at: { warrior: number; foes: number }): number {
    let wins = 0;
    for (let t = 0; t < this.trials; t++) {
      const seed = `${kind}:${level}:${at.warrior}:${at.foes}:${t}`;
      const hero = this.made('hero', { classId: 'warrior', raceId: 'human', level: at.warrior }, 'fighters', seed);
      const foes = Array.from({ length: at.foes }, (_, i) => this.made(`foe${i}`, { raceId: kind, level }, 'goblins', seed));
      const battle = new Battle({ id: 'measure', combatants: [hero, ...foes], abilities: Content.abilities }, seed);
      for (let step = 0; !battle.state.outcome && step < 600; step++) {
        battle.step(Tactics.choose(battle.state, battle.plain(battle.legalCommands())));
      }
      const fled = battle.events.findLast(e => e.type === 'end');
      if (battle.state.outcome === 'fighters' || (fled?.type === 'end' && fled.fled?.team === 'goblins')) { wins++; }
    }
    return wins / this.trials;
  }
  private static made(id: string, context: Record<string, unknown>, team: Fighter['team'], seed: string): Fighter {
    return CombatProjection.fighter(this.content.createCreature(id, context as never, `${seed}:${id}`), team);
  }
}
