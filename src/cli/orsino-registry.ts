// The Orsino registry and the catalogs, tables and inventory generated from it (bin/kyrie orsino <command>).
import { readFileSync, writeFileSync } from 'node:fs';
import { OrsinoCorpus } from './orsino-corpus';
import { Options } from './options';
import { OrsinoExtract } from '../registry/orsino-extract';
import { OrsinoRegistry } from '../registry/orsino-registry';
import { OrsinoReport } from '../registry/orsino-report';
import { KyrLinks } from '../registry/kyr-links';
import { OrsinoTranslate } from '../registry/orsino-translate';
import { CatalogLedger } from '../registry/catalog-ledger';
import { OrsinoBestiary } from '../registry/orsino-bestiary';
import { OrsinoWorld } from '../registry/orsino-world';
import { OrsinoVariants } from '../registry/orsino-variants';
import type { Species } from '../canon/schema';
import type { RegistryEntry } from '../registry/orsino-extract';

type Snapshot = { entries: RegistryEntry[] };
export class OrsinoRegistryTool {
  static readonly usage = 'usage: bin/kyrie orsino generate|report|check|catalog|bestiary|world|variants|inventory'
    + ' [--source ../orsino] [--out data/sources/orsino/registry.json]';
  static async main(args: string[]): Promise<number> {
    const [command = 'generate', ...rest] = args, options = new Options(rest);
    switch (command) {
      case 'generate': this.generate(options.get('source', '../orsino'), options.get('out', 'data/sources/orsino/registry.json')); return 0;
      case 'report': case 'check': return this.check(command, options);
      case 'catalog': this.catalog(); return 0;
      case 'variants': await this.variants(); return 0;
      case 'bestiary': this.bestiary(); return 0;
      case 'world': await this.world(); return 0;
      case 'inventory': await this.inventory(); return 0;
      default: console.error(this.usage); return 1;
    }
  }
  private static snapshot(): Snapshot {
    return JSON.parse(readFileSync('data/sources/orsino/registry.json', 'utf8')) as Snapshot;
  }
  private static registry(): OrsinoRegistry {
    return new OrsinoRegistry(JSON.parse(readFileSync('data/sources/orsino/registry.json', 'utf8')),
      CatalogLedger.combined(JSON.parse(readFileSync('data/sources/orsino/adaptations.json', 'utf8'))));
  }
  private static generate(source: string, out: string) {
    const snapshot = OrsinoExtract.snapshot(OrsinoCorpus.load(source));
    writeFileSync(out, `${JSON.stringify(snapshot, null, 1)}\n`);
    const unresolved = snapshot.entries.flatMap(e => e.references.filter(r => !r.resolved).map(r => `${e.id} -> ${r.ref}`));
    console.log(`${snapshot.entries.length} entries in ${Object.keys(snapshot.families).length} families from orsino@${snapshot.source.revision.slice(0, 12)}`);
    console.log(`${unresolved.length} unresolved references`);
  }
  private static check(command: string, options: Options): number {
    const registry = this.registry(), problems = [...registry.problems(), ...KyrLinks.problems(registry.ledger)];
    problems.forEach(p => console.error(p));
    if (command === 'report') {
      writeFileSync(options.get('report', 'doc/architecture/orsino-coverage.md'), OrsinoReport.render(registry));
    }
    for (const g of registry.gaps().slice(0, 12)) { console.log(`${String(g.entries).padStart(4)}  ${g.feature}`); }
    return problems.length ? 1 : 0;
  }
  // The generated Orsino catalogs: every status, trait, ability, spell, weapon and armour translated from the snapshot.
  private static catalog() {
    const snapshot = this.snapshot();
    const vocabulary = JSON.parse(readFileSync('data/catalog/vocabulary.json', 'utf8')) as
      { saveKinds: Record<string, string>; damageTypes: string[] };
    const generated = new OrsinoTranslate(snapshot.entries, { saveKinds: Object.keys(vocabulary.saveKinds),
      damageTypes: vocabulary.damageTypes, bestiary: OrsinoBestiary.vocabulary(snapshot.entries) }).generate();
    for (const [family, entries] of Object.entries(generated)) {
      const values = Object.values(entries) as { unsupported?: object }[];
      writeFileSync(`data/catalog/orsino/${family}.json`, `${JSON.stringify({ about: `Generated by bin/kyrie orsino`
        + ` catalog from the Orsino snapshot; do not edit. Hand-written entries in data/catalog may override an entry that`
        + ` names the same Orsino source.`, [family]: entries }, null, 1)}\n`);
      console.log(`${family}: ${values.length} entries, ${values.filter(v => v.unsupported).length} not executable`);
    }
  }
  // Orsino's creature aspects (agile, venomous…), their rarities, and its undead templates (skeletal, spectral…), as
  // what each adds to a creature (run after catalog: it keeps only the abilities and traits Kyr has).
  private static async variants() {
    const { Canon } = await import('../canon/canon');
    const { Content } = await import('../content');
    const variants = new OrsinoVariants(this.snapshot().entries, { abilities: new Set(Content.abilities.map(a => a.id)),
      traits: new Set(Object.keys(Canon.traits)) }).generate();
    writeFileSync('data/catalog/orsino/variants.json', `${JSON.stringify({ about: 'Generated by bin/kyrie orsino '
      + 'variants from the Orsino snapshot; do not edit. Creature aspects by rarity, and undead templates: what each adds.',
    ...variants }, null, 1)}\n`);
    console.log(`aspects: ${Object.keys(variants.aspects).length}, templates: ${Object.keys(variants.templates).length}`);
  }
  // Orsino's monster types, elementals and animals as Kyr species (run after catalog: it reads the Kyr catalogs).
  private static bestiary() {
    const hand = (JSON.parse(readFileSync('data/catalog/species.json', 'utf8')) as { species: Record<string, Species> }).species;
    const species = new OrsinoBestiary(this.snapshot().entries, hand).generate();
    writeFileSync('data/catalog/orsino/species.json', `${JSON.stringify({ about: 'Generated by bin/kyrie orsino '
      + 'bestiary from the Orsino snapshot; do not edit. A hand-written species in data/catalog/species.json that names the '
      + 'same Orsino source stands in its place.', species }, null, 1)}\n`);
    const values = Object.values(species);
    console.log(`species: ${values.length} entries, ${values.filter(s => s.omits && Object.keys(s.omits).length > 1).length} leave something out`);
  }
  // Orsino's wonders, traps, shops and riddles as tables generated regions draw from (run after catalog).
  private static async world() {
    const { Canon } = await import('../canon/canon');
    const { Content } = await import('../content');
    const trade = (await import('../../data/generation/tables/trade.json')).default as unknown as
      { merchantType: { groups: Record<string, { stock: [string, number, number][] }> } };
    const tables = new OrsinoWorld(this.snapshot().entries, { statuses: new Set(Object.keys(Canon.conditions)),
      abilities: new Set(Content.abilities.map(a => a.id)), damage: new Set(Content.rules.damageTypes),
      items: new Set(Object.keys(Canon.items)),
      catalog: Canon.items as unknown as Record<string, { source?: { orsino?: string }; value?: number }>,
      outfit: trade.merchantType.groups.chandler!.stock.map(([id]) => id) }).generate();
    writeFileSync('data/generation/scenes/orsino-world.json', `${JSON.stringify({ about: 'Generated by bin/kyrie orsino world '
      + 'from the Orsino snapshot; do not edit. Orsino\'s wonders, traps, shops and riddles, each with its effect in the Kyr '
      + 'effect language and what of it Kyr cannot do (omits).', ...tables }, null, 1)}\n`);
    for (const [k, v] of Object.entries(tables)) {
      const list = Object.values(v) as { effect?: string }[];
      console.log(`${k}: ${list.length}${k === 'wonders' || k === 'traps' ? `, ${list.filter(x => x.effect).length} with an effect Kyr can run` : ''}`);
    }
  }
  // Where every Orsino entry went in Kyr, computed from what Kyr has and draws (run after world and catalog).
  private static async inventory() {
    const { OrsinoInventory } = await import('../registry/orsino-inventory');
    const { OrsinoInventoryReport } = await import('../registry/orsino-inventory-report');
    const inventory = new OrsinoInventory(this.registry()).build();
    writeFileSync('data/sources/orsino/inventory.json', `${JSON.stringify(inventory, null, 1)}\n`);
    writeFileSync('doc/architecture/orsino-inventory.md', OrsinoInventoryReport.render(inventory));
    for (const p of OrsinoInventory.placements) {
      console.log(`${p}: ${inventory.entries.filter(e => e.status === p).length}`);
    }
  }
}
