import { HandbookStatus, Statuses, type Book, type Entry, type Section, type Table } from './model';
import type { Coverage } from './handbooks';

// The books as Markdown, kept in the repository so a change to what the game can play shows in review.
export class HandbookMarkdown {
  static cell(s: string): string { return s.replace(/\|/g, '\\|').replace(/\n/g, ' '); }
  static book(b: Book): string {
    return [`# ${b.title}`, '', ...b.intro.flatMap(p => [p, '']), ...b.sections.flatMap(s => this.section(s, 2))].join('\n');
  }
  static section(s: Section, depth: number): string[] {
    return [`${'#'.repeat(Math.min(depth, 5))} ${s.title}`, '', ...(s.intro ?? []).flatMap(p => [p, '']),
      ...s.table ? [...this.table(s.table), ''] : [], ...(s.entries ?? []).flatMap(e => this.entry(e, depth + 1)),
      ...(s.sections ?? []).flatMap(x => this.section(x, depth + 1))];
  }
  static table(t: Table): string[] {
    return [`| ${t.head.map(h => this.cell(h)).join(' | ')} |`, `|${t.head.map(() => '---').join('|')}|`,
      ...t.rows.map(r => `| ${r.map(c => this.cell(c)).join(' | ')} |`)];
  }
  static entry(e: Entry, depth: number): string[] {
    return [`${'#'.repeat(Math.min(depth, 6))} ${e.title}`, '',
      `*${HandbookStatus.label(e.status)}${e.kind ? ` · ${e.kind}` : ''}* · \`${e.id}\``, '',
      ...e.facts?.length ? [...e.facts.map(([k, v]) => `- ${k}: ${v}`), ''] : [],
      ...(e.rules ?? []).flatMap(r => [r, '']), ...(e.text ?? []).flatMap(t => [`> ${t}`, '']),
      ...(e.notes ?? []).flatMap(n => [`*${n}*`, ''])];
  }
  static coverage(c: Coverage): string {
    const books = Object.values(c.books).map(b => `| ${b.title} | ${Statuses.map(s => b.counts[s]).join(' | ')} |`);
    return ['# Handbook coverage', '', 'Generated by `bin/kyrie handbook`. Every entry in the three books and the '
      + 'status the game gives it; `coverage.json` has each entry.', '',
    `| Book | ${Statuses.map(s => HandbookStatus.label(s)).join(' | ')} |`, `|---|${Statuses.map(() => '---:').join('|')}|`, ...books, '',
    '## Problems', '', ...this.table({ head: ['Book', 'Kind', 'Entry', 'Problem'],
      rows: c.problems.map(p => [p.book, p.kind, `\`${p.entry}\``, p.text]) }), ''].join('\n');
  }
}
